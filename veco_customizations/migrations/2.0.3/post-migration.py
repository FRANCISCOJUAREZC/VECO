"""Fix the Studio-customized sale.order / purchase.order QWeb reports for
Odoo 19, mirroring the account.move fixes in migrations/2.0.2.

These reports are `ir.ui.view` records generated by Odoo Studio, not files
tracked in this repo. They still contained several patterns removed/renamed
by Odoo 19:

- `sale.order.line.product_uom` / `purchase.order.line.product_uom` renamed
  to `product_uom_id`: some Studio duplicates read `line.product_uom.name`
  directly as a python attribute (not through `t-field`), which raises
  ``AttributeError`` since the ORM has no python-level alias for a removed
  field.
- `purchase.order.notes` renamed to `note` ("Terms and Conditions"):
  `t-field="o.notes"` raises a ``KeyError`` in `ir_qweb._get_field`.
- `account.move.line.display_type` used to be ``False``/empty for a regular
  line; Odoo 19 sets it to ``'product'``. Eleven sale.order document
  templates and one purchase.order document template guarded their line
  row with ``t-if="not line.display_type"``, always false now, so orders
  printed with an empty product table.
- `account.document_tax_totals_copy_7` / `_copy_8` (used by two Studio
  sale.order report variants) still read the pre-Odoo-17 tax_totals shape
  (`formatted_amount`, `groups_by_subtotal`) instead of the current
  `subtotals` / `tax_groups` shape, raising a ``KeyError`` on the totals
  block.
- the "Odoo Studio: report_purchaseorder_document copy(1) customization"
  overlay (inherited view on top of
  ``purchase.report_purchaseorder_document_copy_1``) has its own
  `line.product_uom.name` and `o.notes` occurrences that need the same fix.
"""

