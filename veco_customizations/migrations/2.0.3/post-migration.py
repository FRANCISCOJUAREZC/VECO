TAX_TOTALS_TEMPLATES_TO_REWRITE = [
    "account.document_tax_totals_copy_7",
    "account.document_tax_totals_copy_8",
]


def _get_view(env, key):
    return env["ir.ui.view"].search([("key", "=", key)], limit=1)


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})

    for key in set(DISPLAY_TYPE_VIEW_KEYS + PRODUCT_UOM_VIEW_KEYS + NOTES_VIEW_KEYS):
        view = _get_view(env, key)
        if not view:
            continue
        arch = view.arch

        if key in DISPLAY_TYPE_VIEW_KEYS:
            arch = arch.replace(
                't-if="not line.display_type"',
                "t-if=\"line.display_type == 'product' or not line.display_type\"",
            )
        if key in PRODUCT_UOM_VIEW_KEYS:
            arch = arch.replace("line.product_uom.name", "line.product_uom_id.name")
            arch = arch.replace("line.product_uom\"", "line.product_uom_id\"")
        if key in NOTES_VIEW_KEYS:
            arch = arch.replace('t-field="o.notes"', 't-field="o.note"')

        if arch != view.arch:
            view.write({"arch": arch})

    for key in TAX_TOTALS_TEMPLATES_TO_REWRITE:
        view = _get_view(env, key)
        if view:
            new_arch = TAX_TOTALS_TEMPLATE.format(name=key)
            if view.arch != new_arch:
                view.write({"arch": new_arch})

    _fix_purchaseorder_copy_1_overlay(env)


def _fix_purchaseorder_copy_1_overlay(env):
    """Fix `line.product_uom.name` and `o.notes` in the Studio overlay on
    top of `purchase.report_purchaseorder_document_copy_1`."""
    parent = _get_view(env, "purchase.report_purchaseorder_document_copy_1")
    if not parent:
        return
    overlay = env["ir.ui.view"].search([
        ("inherit_id", "=", parent.id),
        ("name", "like", "Odoo Studio:"),
    ], limit=1)
    if not overlay:
        return
    arch = overlay.arch
    arch = arch.replace("line.product_uom.name", "line.product_uom_id.name")
    arch = arch.replace('t-field="o.notes"', 't-field="o.note"')
    if arch != overlay.arch:
        overlay.write({"arch": arch})
